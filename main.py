# 发送模板消息
def send_msg(access_token, openid, template_id, data):
    url = f"https://api.weixin.qq.com/cgi-bin/message/template/send?access_token={access_token}"
    body = {
        "touser": openid,
        "template_id": template_id,
        "data": data
    }
    res = requests.post(url, json=body, timeout=15)
    print("发送返回：", res.json())
    return res.json()

