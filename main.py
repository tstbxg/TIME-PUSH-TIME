# 生日倒计时函数
def get_birthday_tip(birthday_str):
    if not birthday_str or birthday_str.startswith("r") is False:
        return ""
    b_date = birthday_str[1:]
    b = datetime.strptime(b_date, "%Y-%m-%d")
    next_b = b.replace(year=today.year)
    if next_b < today:
        next_b = b.replace(year=today.year+1)
    delta = (next_b - today).days
    if delta == 0:
        return "🎂今天是生日！生日快乐！"
    else:
        return f"🎂距离生日还有{delta}天"

