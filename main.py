# 计算恋爱天数
def calc_love_days():
    start = datetime.strptime(LOVE_START,"%Y-%m-%d").date()
    today = date.today()
    return (today - start).days

# 生日倒计时
def get_birthday_text():
    today = date.today()
    txt = ""
    for b in BIRTHDAY_LIST:
        bdt = datetime.strptime(b,"%Y-%m-%d").date()
        next_b = date(today.year, bdt.month, bdt.day)
        if next_b < today:
            next_b = date(today.year+1, bdt.month, bdt.day)
        diff = (next_b - today).days
        txt += f"🎂{b[:4]}生日还有{diff}天\n"
    return txt.strip()

